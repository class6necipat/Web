//Random picker
let siswa = [
    "Fadil",
    "Adzkia",
    "Alifa",
    "Allea",
    "Amora",
    "Avika",
    "Davina",
    "Byan",
    "Kaila",
    "Alif",
    "Agis",
    "Sckar",
    "Hani",
    "Wingka",
    "Zahran",
    "Adibah"
];

let hasilrandom = document.getElementById("hasil-random");
let tombolrandom = document.getElementById("tombol-random");

tombolrandom.addEventListener("click", function() {

    tombolrandom.disabled = true;

    let animasi = setInterval(function() {
        let indexrandom = Math.floor(Math.random() * siswa.length);

        hasilrandom.textContent = siswa[indexrandom];
    }, 100);

    setTimeout(function() {
        clearInterval(animasi);

        let indexrandom = Math.floor(Math.random() * siswa.length);

        hasilrandom.textContent = siswa[indexrandom];

        tombolrandom.disabled = false;
    }, 1500);

});

//theme

let tomboltheme = document.getElementById("theme-toggle")

tomboltheme.addEventListener("click", function(){
    document.body.classList.toggle("dark-mode")

    if (document.body.classList.contains("dark-mode")) {
        tomboltheme.textContent = "☀️ light-mode";
    } else  {
        tomboltheme.textContent = "🌙 dark-mode"
    }
})

